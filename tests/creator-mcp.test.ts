import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile, readdir } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
import { z } from 'zod';
import { createOperations } from '../packages/application/operations.ts';
import { createCreatorOperations, createCreatorIngestion, projectCreatorDna, type CreatorRepository } from '../packages/application/creator-operations.ts';
import { creatorContracts, StoredCreatorOutput, GetCreatorDnaOutput, CorrectCreatorDnaOutput } from '../packages/contracts/creator-operations.ts';
import { creatorAnalysisFixture } from '../packages/contracts/fixtures/creator-profile.ts';
import { SaveProjectOutput } from '../packages/contracts/index.ts';
import { handleMcp } from '../apps/worker/mcp.ts';
import { oauthScopes } from '../packages/auth/index.ts';
import { fixtureAuth, config } from './auth-fixtures.ts';
import { createInput, accountA } from './fixtures.ts';

test('Creator MCP reads, render and corrections use signed identity, real SQL and public projection', async t => {
  const db = new PGlite(); t.after(() => db.close());
  await db.exec('create role anon; create role authenticated; create role service_role bypassrls; create role supabase_auth_admin; grant usage on schema public to service_role; alter default privileges in schema public grant all on tables to service_role;');
  for (const file of (await readdir('supabase/migrations')).filter(f => f.endsWith('.sql')).sort()) await db.exec(await readFile(`supabase/migrations/${file}`, 'utf8'));
  await db.exec(await readFile('supabase/seed.sql', 'utf8'));
  const identity = await fixtureAuth();
  let calls = 0;
  const repository: CreatorRepository = { call: (operation, owner, input) => db.transaction(async tx => {
    calls++; await tx.exec('set local role service_role');
    return (await tx.query<{ result: unknown }>(`select public.kettle_${operation}($1::uuid,$2::jsonb) as result`, [owner, JSON.stringify(input)])).rows[0]!.result;
  }) };
  const operations = createOperations(identity.verifier, { call: (op, owner, input) => db.transaction(async tx => {
    await tx.exec('set local role service_role');
    return (await tx.query<{ result: unknown }>(`select public.kettle_${op}($1::uuid,$2::jsonb) as result`, [owner, JSON.stringify(input)])).rows[0]!.result;
  }) });
  const auth = { config, verifier: identity.verifier, operations, creatorOperations: createCreatorOperations(identity.verifier, repository) };
  const token = await identity.token();
  const project = SaveProjectOutput.parse(await operations.execute('save_project', token, createInput())); assert.ok(project.ok);
  const analysis = creatorAnalysisFixture();
  const stored = StoredCreatorOutput.parse(await createCreatorIngestion(repository)(accountA, {project_id:project.data.project.id,request_id:crypto.randomUUID(),analysis})); assert.ok(stored.ok);
  const rpc = async (method: string, params: unknown, credential?: string, enabled = true) => handleMcp(new Request(config.resource, {method:'POST',headers:{'Content-Type':'application/json',Accept:'application/json, text/event-stream',...(credential?{Authorization:`Bearer ${credential}`}:{})},body:JSON.stringify({jsonrpc:'2.0',id:1,method,params})}), enabled ? auth : undefined);
  const call = async (name: string, args: unknown, credential?: string) => (await (await rpc('tools/call',{name,arguments:args},credential)).json() as {result:{structuredContent:unknown;content:{text:string}[];isError:boolean;_meta?:Record<string,string[]>};error?:unknown});
  const listing = await (await rpc('tools/list',{})).json() as {result:{tools:Record<string,unknown>[]}};
  for (const name of ['get_creator_dna','render_creator_dna','correct_creator_dna']) {
    const tool = listing.result.tools.find(t => t.name === name)!; assert.ok(tool);
    const contract = creatorContracts[name === 'correct_creator_dna' ? name : 'get_creator_dna'];
    assert.deepEqual(tool.inputSchema,{...z.toJSONSchema(contract.input),type:'object'});
    assert.deepEqual(tool.outputSchema,{...z.toJSONSchema(contract.output),type:'object'});
    assert.deepEqual(tool.securitySchemes,[{type:'oauth2',scopes:[...oauthScopes]}]);
  }
  assert.ok(!listing.result.tools.some(t => /ingest|scan|generate/.test(String(t.name))));
  const input = {dna_id:stored.data.dna_id};
  const shown = (await call('render_creator_dna',input,token)).result;
  const view = GetCreatorDnaOutput.parse(shown.structuredContent); assert.ok(view.ok);
  assert.equal(view.data.dna.contains_fixture_data,true);
  assert.deepEqual(JSON.parse(shown.content[0]!.text),shown.structuredContent);
  for (const secret of ['requested_cursor','permitted_uses','provider_endpoint','cost_attempts']) assert.ok(!JSON.stringify(shown).includes(secret));
  const before = calls;
  const denied = (await call('render_creator_dna',input)).result;
  assert.match(denied._meta!['mcp/www_authenticate']![0]!,/invalid_token/);
  const noScope = (await call('get_creator_dna',input,await identity.token({riff_permissions:['account:read']}))).result;
  assert.match(noScope._meta!['mcp/www_authenticate']![0]!,/insufficient_scope/);
  const injected = await call('get_creator_dna',{...input,account_id:accountA},token); assert.ok(injected.error || injected.result.isError);
  assert.equal(calls,before);
  const foreign = await identity.token({sub:'user-b'});
  assert.deepEqual((await call('render_creator_dna',input,foreign)).result,(await call('render_creator_dna',{dna_id:crypto.randomUUID()},foreign)).result);
  const correction = {...input,expected_version:1,request_id:crypto.randomUUID(),corrections:view.data.dna.claims.map(c=>({claim_id:c.id,statement:'User corrected fictional context'}))};
  const updated = CorrectCreatorDnaOutput.parse((await call('correct_creator_dna',correction,token)).result.structuredContent); assert.ok(updated.ok);
  assert.equal(updated.data.dna.version,2);
  assert.equal(updated.data.dna.contains_fixture_data,true,'fictional origin survives corrections');
  assert.deepEqual(updated.data.dna.evidence,view.data.dna.evidence,'correction preserves original evidence lineage');
  const hidden = structuredClone(stored.data);
  for (const o of [...hidden.analysis.scan.profile_observations,...hidden.analysis.scan.video_observations]) o.provenance.permission.permitted_uses = ['store','model_processing'];
  const withheld = projectCreatorDna(hidden);
  assert.equal(withheld.evidence.length,0);
  assert.equal(withheld.contains_fixture_data,true,'withholding evidence cannot erase fictional origin');
  assert.deepEqual((await call('correct_creator_dna',correction,token)).result.structuredContent,updated);
  const reopened = GetCreatorDnaOutput.parse((await call('render_creator_dna',input,token)).result.structuredContent); assert.ok(reopened.ok); assert.equal(reopened.data.dna.version,2);
  const history = GetCreatorDnaOutput.parse((await call('get_creator_dna',{...input,version:1},token)).result.structuredContent); assert.deepEqual(history,view);
  const stale = (await call('correct_creator_dna',{...correction,request_id:crypto.randomUUID()},token)).result; assert.equal(stale.isError,true); assert.match(stale.content[0]!.text,/VERSION_CONFLICT/);
  const resource = await (await rpc('resources/read',{uri:'ui://kettle/creator-review-v2.html'})).json() as {result:{contents:{text:string;_meta:Record<string,unknown>}[]}};
  assert.match(resource.result.contents[0]!.text,/ui\/initialize/);
  assert.ok(!resource.result.contents[0]!.text.includes(stored.data.dna_id));
  const unavailable = await (await rpc('tools/list',{},undefined,false)).json() as {result:{tools:{name:string}[]}};
  assert.deepEqual(unavailable.result.tools.map(t=>t.name),['kettle_diagnostic']);
  identity.block();
  assert.equal((await rpc('tools/call',{name:'correct_creator_dna',arguments:correction},token)).status,401);
});
